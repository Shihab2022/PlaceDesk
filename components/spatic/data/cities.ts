import type { CityDef } from "./types";

/**
 * City registry.
 *
 * Delhi is backed by the real `/api/pois?path=site_analysis_delhi/*.json`
 * datasets (`useApi: true`). All other cities fall back to the schema-identical
 * deterministic mock generator until real datasets land.
 */
function makeCity(
  id: string,
  label: string,
  country: string,
  lat: number,
  lng: number,
  zoom: number,
  useApi: boolean,
  areas: [string, number, number][],
  pincodePrefix: string,
  pincodeLength: number,
  roads: string[],
): CityDef {
  return {
    id,
    label,
    country,
    center: { lat, lng },
    zoom,
    useApi,
    districts: areas.map(([name, la, ln]) => ({ name, lat: la, lng: ln })),
    pincode: pincodePrefix,
    pincodeLength,
    roads,
  };
}

